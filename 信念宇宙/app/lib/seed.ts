type SeedEdgeInput = Omit<
  BeliefEdge,
  "bidirectional" | "confidence" | "sensitive" | "sourceExcerptIds"
> & {
  bidirectional?: boolean;
  confidence?: Confidence;
  sensitive?: boolean;
};

function seedEdge(input: SeedEdgeInput): BeliefEdge {
  return {
    ...input,
    bidirectional: input.bidirectional ?? input.kind === "conflicts-with",
    confidence: input.confidence ?? "medium",
    sensitive: input.sensitive ?? false,
    sourceExcerptIds: [
      ...new Set(input.provenance.map((p) => provenanceSourceIds[p])),
    ],
  };
}

